export const LANGUAGES = ['en', 'fr']

export function translator(lang) {
  const words = WORDS[lang] ?? WORDS.en

  return (key, vars = {}) => {
    let text = words[key] ?? WORDS.en[key]
    if (text === undefined) return undefined
    if (typeof text === 'object') text = vars.n === 1 ? text.one : text.other

    return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] === undefined ? '' : String(vars[name])))
  }
}

// What an agent is called on screen.
export function agentName(source) {
  if (!source || source === 'claude-code') return 'Claude Code'
  if (source === 'grok') return 'Grok'

  return source.charAt(0).toUpperCase() + source.slice(1)
}
